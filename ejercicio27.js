// Crea una función que reciba un número y devuelva su raíz cuadrada.
function calcularRaizCuadrada(numero) {
  return Math.sqrt(numero);
}

// Crea una variable que reciba un objeto.
const objetoEjemplo = {
  nombre: "Usuario",
  edad: 30,
  activo: true,
};

// Ejemplos de uso:
console.log(calcularRaizCuadrada(25)); // Devuelve 5
console.log(objetoEjemplo);
